using Content.Client._Orbitra.Stylesheets; // Orbitra-Edit
using Content.Client._Orbitra.UserInterface; // Orbitra-Edit
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.PDA;

[GenerateTypedNameReferences]
public sealed partial class PdaNavigationButton : OrbitraContainerButton // Orbitra-Edit - общие состояния и фокус
{
    private bool _isActive = true;

    public SpriteSpecifier? IconTexture
    {
        set
        {
            Icon.Visible = value != null;
            Label.Visible = value == null;

            if (value is not null)
                Icon.SetFromSpriteSpecifier(value);
        }
    }

    public string? LabelText
    {
        get => Label.Text;
        set => Label.Text = value;
    }

    // Orbitra added start - обрезаем только длинные заголовки открытых приложений.
    public bool ClipLabelText
    {
        get => Label.ClipText;
        set => Label.ClipText = value;
    }
    // Orbitra added end

    // Orbitra edit start - состояние вкладки показывается штатным pressed.
    public bool IsCurrent
    {
        get => Pressed;
        set => Pressed = value;
    }

    public bool IsActive
    {
        get => _isActive;
        set
        {
            _isActive = value;
            Icon.ModulateSelfOverride = value ? OrbitraPalettes.IconHovered : OrbitraPalettes.IconPressed;
        }
    }
    // Orbitra edit end

    public PdaNavigationButton()
    {
        RobustXamlLoader.Load(this);
        Icon.DisplayRect.Stretch = TextureRect.StretchMode.KeepAspectCentered; // Orbitra-Edit - один размер иконок
        IsActive = true; // Orbitra-Edit
    }
}
