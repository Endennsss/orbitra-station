using System.Numerics;
using Content.Client._Orbitra.Pda; // Orbitra-Edit
using Content.Client._Orbitra.Stylesheets;
using Content.Client._Orbitra.UserInterface; // Orbitra-Edit
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.PDA;

[Virtual]
[GenerateTypedNameReferences]
public partial class PdaWindow : BaseWindow
{
    // Orbitra added start - приглушаем расцветку, сохраняя оттенок конкретного КПК.
    public string? BorderColor
    {
        get => Background.ActualModulateSelf.ToHex();

        set
        {
            var color = Color.FromHex(value, OrbitraPalettes.PanelHighlight);
            Background.ModulateSelfOverride = Color.InterpolateBetween(OrbitraPalettes.PanelHighlight, color, 0.54f);
        }
    }
    // Orbitra added end

    public PdaWindow()
    {
        RobustXamlLoader.Load(this);

        CloseButton.OnPressed += _ => Close();
        XamlChildren = ContentsContainer.Children;

        CaseInterior.Margin = new Thickness(OrbitraPdaTrim.Inset); // Orbitra-Edit - экран внутри обода
        Header.MinHeight = OrbitraUiMetrics.HeaderHeight; // Orbitra-Edit - общая высота шапки
        BorderColor = null; // Orbitra-Edit - нейтральный корпус по умолчанию
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        // Orbitra-Edit - перетаскиваем за верхнюю рамку, не за содержимое программ.
        return relativeMousePos.Y < Header.GlobalPosition.Y - GlobalPosition.Y + Header.Size.Y
            ? DragMode.Move
            : DragMode.None;
    }
}
