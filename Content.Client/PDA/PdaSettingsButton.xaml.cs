using Content.Client._Orbitra.Stylesheets; // Orbitra-Edit
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility; // Orbitra-Edit

namespace Content.Client.PDA;

[GenerateTypedNameReferences]
public sealed partial class PdaSettingsButton : ContainerButton
{
    public string? Text
    {
        get => OptionName.Text;
        set
        {
            OptionName.Text = value;
            ToolTip = value;
        }
    }

    // Orbitra edit start - перенос длинных описаний.
    private string? _description;

    public string? Description
    {
        get => _description;
        set
        {
            _description = value;
            var message = new FormattedMessage();
            message.AddText(value ?? string.Empty);
            OptionDescription.SetMessage(message, defaultColor: OrbitraPalettes.IconHovered);
        }
    }

    // Orbitra edit end

    public PdaSettingsButton()
    {
        RobustXamlLoader.Load(this);
    }
}
