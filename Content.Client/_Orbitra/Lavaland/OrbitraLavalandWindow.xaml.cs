using Content.Client.UserInterface.Controls;
using Content.Shared._Orbitra.Lavaland;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Orbitra.Lavaland;

[GenerateTypedNameReferences]
public sealed partial class OrbitraLavalandWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    private TimeSpan? _deadline;
    private bool _boarding;
    private int _seconds = -1;

    public OrbitraLavalandWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    internal void Display(LavalandConsoleState state, LavalandSide terminal)
    {
        var location = SideName(state.Location);
        var destination = SideName(state.Destination);
        Location.SetMessage(state.Status switch
        {
            LavalandFerryStatus.Preparing or LavalandFerryStatus.Unavailable => _loc.GetString("orbitra-lavaland-no-fix"),
            LavalandFerryStatus.Blocked when !state.CanRequest => _loc.GetString("orbitra-lavaland-holding", ("port", destination)),
            LavalandFerryStatus.Transit => _loc.GetString("orbitra-lavaland-target", ("port", destination)),
            _ => location,
        });
        var status = state.Status switch
        {
            LavalandFerryStatus.Docked => "orbitra-lavaland-docked",
            LavalandFerryStatus.Boarding => "orbitra-lavaland-boarding",
            LavalandFerryStatus.Transit => "orbitra-lavaland-transit",
            LavalandFerryStatus.Blocked => state.BlockReason switch
            {
                LavalandBlockReason.Occupied => "orbitra-lavaland-occupied",
                LavalandBlockReason.Obstructed => "orbitra-lavaland-obstructed",
                LavalandBlockReason.MissingDock => "orbitra-lavaland-missing-dock",
                LavalandBlockReason.Undocked => "orbitra-lavaland-undocked",
                LavalandBlockReason.SurfaceUnavailable => "orbitra-lavaland-surface-unavailable",
                _ => "orbitra-lavaland-blocked",
            },
            LavalandFerryStatus.Preparing => "orbitra-lavaland-preparing",
            _ => "orbitra-lavaland-unavailable",
        };
        var message = _loc.GetString(status);
        if (state.Status == LavalandFerryStatus.Blocked && !state.CanRequest)
            message += " " + _loc.GetString("orbitra-lavaland-auto-arrival");
        Status.SetMessage(message);
        RequestButton.Text = _loc.GetString(state.Location == terminal ? "orbitra-lavaland-send" : "orbitra-lavaland-call");
        RequestButton.Disabled = !state.CanRequest;
        _deadline = state.Deadline;
        _boarding = state.Status == LavalandFerryStatus.Boarding;
        _seconds = -1;
        Countdown.Visible = _deadline.HasValue;
        UpdateCountdown();
    }

    private string SideName(LavalandSide side) =>
        _loc.GetString(side == LavalandSide.Station ? "orbitra-lavaland-station" : "orbitra-lavaland-outpost");

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCountdown();
    }

    private void UpdateCountdown()
    {
        if (_deadline is not { } deadline)
            return;

        var remaining = Math.Max(0, (int)Math.Ceiling((deadline - _timing.CurTime).TotalSeconds));
        if (_seconds == remaining)
            return;

        _seconds = remaining;
        Countdown.Text = _loc.GetString(_boarding ? "orbitra-lavaland-until-departure" : "orbitra-lavaland-until-arrival",
            ("seconds", remaining));
    }
}
