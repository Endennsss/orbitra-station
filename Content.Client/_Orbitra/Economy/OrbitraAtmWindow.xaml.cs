using Content.Client.UserInterface.Controls;
using Content.Shared._Orbitra.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Orbitra.Economy;

[GenerateTypedNameReferences]
public sealed partial class OrbitraAtmWindow : FancyWindow
{
    public event Action? InsertCardRequested;
    public event Action? EjectCardRequested;
    public event Action? DepositRequested;
    public event Action<int>? WithdrawRequested;
    public event Action<int, int>? TransferRequested;

    private int _account;
    private int _balance;
    private bool _cardInserted;

    public OrbitraAtmWindow()
    {
        RobustXamlLoader.Load(this);
        Amount.OnTextChanged += _ => UpdateActions();
        Recipient.OnTextChanged += _ => UpdateActions();
        CardButton.OnPressed += _ =>
        {
            if (_cardInserted)
                EjectCardRequested?.Invoke();
            else
                InsertCardRequested?.Invoke();
        };
        DepositButton.OnPressed += _ => DepositRequested?.Invoke();
        WithdrawButton.OnPressed += _ =>
        {
            if (int.TryParse(Amount.Text, out var amount))
                WithdrawRequested?.Invoke(amount);
        };
        TransferButton.OnPressed += _ =>
        {
            if (int.TryParse(Amount.Text, out var amount) && int.TryParse(Recipient.Text, out var recipient))
                TransferRequested?.Invoke(recipient, amount);
        };
        UpdateActions();
    }

    /// <summary>Обновляет личные данные и список последних операций.</summary>
    public void UpdateAccount(OrbitraAtmSnapshotMessage snapshot)
    {
        _account = snapshot.Account;
        _balance = snapshot.Balance;
        _cardInserted = snapshot.CardInserted;
        var identified = _account != 0;
        LoginNotice.Visible = !identified;
        LoginNotice.Text = Loc.GetString(_cardInserted ? "orbitra-atm-card-occupied" : "orbitra-atm-login");
        CardButton.Text = Loc.GetString(_cardInserted ? "orbitra-atm-eject-card" : "orbitra-atm-insert-card");
        CardButton.Disabled = _cardInserted && !identified;
        Operations.Visible = HistoryTitle.Visible = HistoryScroll.Visible = identified;
        AccountLabel.Text = identified
            ? Loc.GetString("orbitra-atm-account", ("account", _account))
            : Loc.GetString("orbitra-atm-title");
        BalanceLabel.Text = identified ? Loc.GetString("orbitra-atm-balance", ("amount", _balance)) : string.Empty;
        HistoryList.RemoveAllChildren();

        for (var index = snapshot.Entries.Length - 1; index >= 0; index--)
        {
            var entry = snapshot.Entries[index];
            var key = entry.Kind switch
            {
                OrbitraBankEntryKind.StartingBalance => "orbitra-atm-entry-start",
                OrbitraBankEntryKind.Salary => "orbitra-atm-entry-salary",
                OrbitraBankEntryKind.Deposit => "orbitra-atm-entry-deposit",
                OrbitraBankEntryKind.Withdrawal => "orbitra-atm-entry-withdraw",
                OrbitraBankEntryKind.Transfer => "orbitra-atm-entry-transfer",
                OrbitraBankEntryKind.Purchase => "orbitra-atm-entry-purchase",
                _ => "orbitra-atm-entry-unknown",
            };
            var amount = entry.Amount.ToString("+#;-#;0");
            var text = entry.Kind == OrbitraBankEntryKind.Transfer
                ? Loc.GetString(key, ("amount", amount), ("account", entry.RelatedAccount))
                : Loc.GetString(key, ("amount", amount));
            HistoryList.AddChild(new Label { Text = text, ClipText = true });
        }

        UpdateActions();
    }

    private void UpdateActions()
    {
        var validAmount = _account != 0 && int.TryParse(Amount.Text, out var amount) && amount > 0 && amount <= _balance;
        WithdrawButton.Disabled = !validAmount;
        TransferButton.Disabled = !validAmount || !int.TryParse(Recipient.Text, out var recipient) ||
            recipient <= 0 || recipient == _account;
        DepositButton.Disabled = _account == 0;
    }
}
