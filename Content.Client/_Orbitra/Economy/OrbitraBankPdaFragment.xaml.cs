using System.Globalization;
using Content.Client.Message;
using Content.Shared._Orbitra.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Timer = Robust.Shared.Timing.Timer;

namespace Content.Client._Orbitra.Economy;

[GenerateTypedNameReferences]
public sealed partial class OrbitraBankPdaFragment : ScrollContainer
{
    private readonly IClipboardManager _clipboard = IoCManager.Resolve<IClipboardManager>();
    private int _account;
    private int _balance;
    private bool _receivedAccount;

    public event Action<int, int>? TransferRequested;

    public OrbitraBankPdaFragment()
    {
        RobustXamlLoader.Load(this);
        LoginNotice.SetMarkup(Loc.GetString("orbitra-bank-pda-loading"));
        Recipient.OnTextChanged += _ => UpdateActions();
        Amount.OnTextChanged += _ => UpdateActions();
        CopyAccountButton.OnPressed += _ => _clipboard.SetText(_account.ToString(CultureInfo.InvariantCulture));
        TransferButton.OnPressed += _ =>
        {
            if (TryReadTransfer(out var recipient, out var amount))
                TransferRequested?.Invoke(recipient, amount);
        };
    }

    internal void RequestAccount(Action request, int attempts = 8)
    {
        if (Parent == null || _receivedAccount)
            return;

        if (attempts == 0)
        {
            LoginNotice.SetMarkup(Loc.GetString("orbitra-bank-pda-load-failed"));
            return;
        }

        // При предсказанном открытии окна сервер может ещё не знать о подписке на интерфейс.
        request();
        Timer.Spawn(500, () => RequestAccount(request, attempts - 1));
    }

    public void UpdateAccount(OrbitraBankPdaState state)
    {
        _receivedAccount = true;
        _account = state.Account;
        _balance = state.Balance;
        AccountView.Visible = _account != 0;
        LoginNotice.Visible = !AccountView.Visible;
        if (LoginNotice.Visible)
        {
            LoginNotice.SetMarkup(Loc.GetString(state.CardInserted ? "orbitra-bank-pda-wrong-id" : "orbitra-bank-pda-insert-id"));
        }

        AccountLabel.Text = _account == 0 ? string.Empty : Loc.GetString("orbitra-atm-account", ("account", _account));
        BalanceLabel.Text = _account == 0 ? string.Empty : Loc.GetString("orbitra-atm-balance", ("amount", _balance));
        History.RemoveAllChildren();
        for (var i = state.Entries.Length - 1; i >= 0; i--)
        {
            var text = OrbitraBankUi.FormatEntry(state.Entries[i]);
            History.AddChild(new Label { Text = text, ClipText = true, ToolTip = text });
        }
        UpdateActions();
    }

    private void UpdateActions() => TransferButton.Disabled = !TryReadTransfer(out _, out _);

    private bool TryReadTransfer(out int recipient, out int amount)
    {
        var validRecipient = int.TryParse(Recipient.Text, out recipient) && recipient > 0 && recipient != _account;
        var validAmount = int.TryParse(Amount.Text, out amount) && amount > 0 && amount <= _balance;
        return _account != 0 && validRecipient && validAmount;
    }
}
