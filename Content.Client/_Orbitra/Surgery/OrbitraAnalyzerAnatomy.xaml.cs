namespace Content.Client._Orbitra.Surgery;

/// <summary>Связывает области на схеме с результатами последнего осмотра пациента.</summary>
[GenerateTypedNameReferences]
public sealed partial class OrbitraAnalyzerAnatomy : BoxContainer
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private static readonly SurgeryInjury[] Findings =
        [SurgeryInjury.Missing, SurgeryInjury.InternalBleeding, SurgeryInjury.Fracture,
         SurgeryInjury.Shrapnel, SurgeryInjury.Splinted, SurgeryInjury.Bandaged];
    private readonly Dictionary<SurgeryZone, ZoneRow> _rows = new();
    private Dictionary<SurgeryZone, SurgeryInjury>? _injuries;
    private Dictionary<SurgeryOrgan, SurgeryOrganCondition>? _organs;
    private ScanEffects _effects;
    private string? _details;
    private EntityUid? _patient;

    private sealed record ZoneRow(OrbitraContainerButton Button, RichTextLabel Label, string Name)
    {
        public string? Summary;
    }

    private readonly record struct OrganEffects(float HeartRecovery, float HeartLoss, float BreathFraction, float LiverInterval);
    private readonly record struct ScanEffects(OrbitraTraumaPrototype? Trauma, float TickMultiplier, OrganEffects? Organs);

    public OrbitraAnalyzerAnatomy()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        BodyMap.ZonePressed += InspectZone;
        BodyMap.DescribeZone = zone => _rows[zone].Summary ?? _rows[zone].Name;

        foreach (var zone in OrbitraTraumaEffectsSystem.Zones)
        {
            var button = new OrbitraContainerButton { ToggleMode = true, HorizontalExpand = true };
            button.AddStyleClass(ContainerButton.StyleClassButton);
            button.AddStyleClass("OrbitraCompactRow");
            button.OnPressed += _ => InspectZone(zone);
            var label = new RichTextLabel { HorizontalExpand = true };
            button.AddChild(label);
            ZoneButtons.AddChild(button);
            _rows.Add(zone, new ZoneRow(button, label, _loc.GetString($"orbitra-surgery-zone-{zone.ToString().ToLowerInvariant()}")));
        }
    }

    protected override Vector2 MeasureOverride(Vector2 availableSize)
    {
        var orientation = availableSize.X < 360 ? LayoutOrientation.Vertical : LayoutOrientation.Horizontal;
        if (Columns.Orientation != orientation)
        {
            Columns.Orientation = orientation;
            BodyMap.SetWidth = orientation == LayoutOrientation.Vertical ? float.NaN : 156f;
        }
        return base.MeasureOverride(availableSize);
    }

    internal void Clear()
    {
        foreach (var row in _rows.Values)
        {
            row.Button.Pressed = false;
            row.Button.Visible = false;
            row.Button.ToolTip = null;
            row.Label.Clear();
            row.Summary = null;
        }
        _patient = null;
        _injuries = null;
        _organs = null;
        _effects = default;
        _details = null;
        BodyMap.Selected = null;
        BodyMap.SetReadings(null, null);
        ZoneName.Text = null;
        ZoneDetails.Clear();
        Visible = false;
    }

    internal void SetReadings(Dictionary<SurgeryZone, SurgeryInjury>? injuries,
        Dictionary<SurgeryOrgan, SurgeryOrganCondition>? organs, EntityUid patient)
    {
        if (_patient != patient)
        {
            Clear();
            _patient = patient;
        }
        // У предсказанного обновления общих показателей нет серверного снимка травм.
        if (injuries == null || injuries.Count == 0 && _injuries == null)
            return;

        var effects = ReadEffects(patient);
        if (_effects == effects && _injuries?.DictionaryEquals(injuries) == true &&
            (_organs == null ? organs == null : organs != null && _organs.DictionaryEquals(organs)))
            return;

        _effects = effects;
        _injuries = new(injuries);
        _organs = organs == null ? null : new(organs);
        Visible = injuries.Count > 0;
        SurgeryZone? first = null;
        SurgeryZone? firstFinding = null;
        foreach (var (zone, row) in _rows)
        {
            row.Button.Visible = injuries.TryGetValue(zone, out var injury);
            if (!row.Button.Visible)
                continue;
            first ??= zone;
            var marked = injury != SurgeryInjury.None || zone == SurgeryZone.Torso && OrbitraOrganSystem.HasFindings(organs);
            var summary = row.Name;
            if (marked)
            {
                firstFinding ??= zone;
                summary = _loc.GetString("orbitra-analyzer-anatomy-zone-findings", ("zone", row.Name),
                    ("findings", FindingNames(zone, injury)));
            }
            if (row.Summary == summary)
                continue;
            row.Summary = summary;
            row.Label.SetMessage(summary, marked ? Color.LightSalmon : null);
            row.Button.ToolTip = summary;
        }

        BodyMap.SetReadings(_injuries, _organs);
        if (first == null)
        {
            Clear();
            return;
        }
        var selection = BodyMap.Selected;
        if (selection == null || !injuries.ContainsKey(selection.Value))
            selection = firstFinding ?? (injuries.ContainsKey(SurgeryZone.Torso) ? SurgeryZone.Torso : first.Value);
        SelectZone(selection.Value);
    }

    // Параметры фиксируются при сканировании. Области остаются доступными после потери связи.
    private ScanEffects ReadEffects(EntityUid patient)
    {
        var profile = _effects.Trauma;
        if (_entity.TryGetComponent<OrbitraSurgicalPatientComponent>(patient, out var surgical))
            _prototype.TryIndex(surgical.TraumaProfile, out profile);
        var multiplier = _injuries == null ? 1f : _effects.TickMultiplier;
        if (_entity.TryGetComponent<BloodstreamComponent>(patient, out var blood))
            multiplier = blood.UpdateIntervalMultiplier;
        var organs = _effects.Organs;
        if (_entity.TryGetComponent<OrbitraHumanOrganPatientComponent>(patient, out var physiology))
            organs = new OrganEffects(physiology.DamagedHeartRecovery, physiology.FailedHeartBloodLoss,
                physiology.DamagedBreathFraction, physiology.DamagedLiverInterval);
        return new ScanEffects(profile, multiplier, organs);
    }

    private string FindingNames(SurgeryZone zone, SurgeryInjury injuries)
    {
        var names = new List<string>();
        foreach (var finding in Findings)
        {
            if ((injuries & finding) != 0)
                names.Add(InjuryName(finding));
        }
        if (zone == SurgeryZone.Torso && _organs != null)
        {
            foreach (var organ in OrbitraOrganSystem.Kinds)
            {
                if (_organs.TryGetValue(organ, out var condition) && condition != SurgeryOrganCondition.Healthy)
                    names.Add(OrganReading(organ, condition));
            }
        }
        return string.Join(", ", names);
    }

    private void InspectZone(SurgeryZone zone)
    {
        SelectZone(zone);
        // Высота описания известна после раскладки. Фоновое обновление показаний не прокручивает окно.
        UserInterfaceManager.DeferAction(() =>
        {
            if (!VisibleInTree || BodyMap.Selected != zone)
                return;
            for (var parent = Parent; parent != null; parent = parent.Parent)
            {
                if (parent is not ScrollContainer scroll)
                    continue;
                var top = ReadingCard.GlobalPosition.Y - scroll.GlobalPosition.Y;
                var overflow = Math.Max(0, top + ReadingCard.Height - scroll.Height);
                scroll.VScrollTarget = scroll.VScroll + Math.Min(top, overflow);
                return;
            }
        });
    }

    private void SelectZone(SurgeryZone zone)
    {
        if (_injuries?.TryGetValue(zone, out var injuries) != true)
            return;
        BodyMap.Selected = zone;
        foreach (var (region, row) in _rows)
            row.Button.Pressed = region == zone;
        if (ZoneName.Text != _rows[zone].Name)
            ZoneName.Text = _rows[zone].Name;
        var details = DescribeFindings(zone, injuries);
        if (_details == details)
            return;
        ZoneDetails.SetMessage(details);
        _details = details;
    }

    private string InjuryName(SurgeryInjury injury) => _loc.GetString($"orbitra-surgery-injury-{injury.ToString().ToLowerInvariant()}");

    private string OrganReading(SurgeryOrgan organ, SurgeryOrganCondition condition) =>
        _loc.GetString("orbitra-surgery-organ-reading",
            ("organ", _loc.GetString($"orbitra-surgery-organ-{organ.ToString().ToLowerInvariant()}")),
            ("condition", _loc.GetString($"orbitra-surgery-organ-condition-{condition.ToString().ToLowerInvariant()}")));

    private string DescribeFindings(SurgeryZone zone, SurgeryInjury injuries)
    {
        var lines = new List<string>();
        foreach (var finding in Findings)
        {
            if ((injuries & finding) == 0)
                continue;
            var effect = InjuryEffect(zone, finding, injuries);
            lines.Add(DescribeEffect(InjuryName(finding), effect));
        }
        if (injuries == SurgeryInjury.None && (zone != SurgeryZone.Torso || !OrbitraOrganSystem.HasFindings(_organs)))
            lines.Add(InjuryName(SurgeryInjury.None));

        if (zone == SurgeryZone.Torso && _organs != null)
        {
            foreach (var organ in OrbitraOrganSystem.Kinds)
            {
                if (_organs.TryGetValue(organ, out var condition))
                    lines.Add(DescribeEffect(OrganReading(organ, condition), OrganEffect(organ, condition)));
            }
        }
        return string.Join("\n", lines);
    }

    private string DescribeEffect(string name, string? effect) => effect == null ? name :
        _loc.GetString("orbitra-analyzer-anatomy-finding-effect", ("finding", name), ("effect", effect));

    private string? InjuryEffect(SurgeryZone zone, SurgeryInjury finding, SurgeryInjury injuries)
    {
        var leg = zone is SurgeryZone.LeftLeg or SurgeryZone.RightLeg;
        var arm = zone is SurgeryZone.LeftArm or SurgeryZone.RightArm;
        if (finding == SurgeryInjury.Missing)
        {
            if (arm)
                return _loc.GetString("orbitra-analyzer-anatomy-hand-missing");
            if (!leg)
                return null;
            var other = zone == SurgeryZone.LeftLeg ? SurgeryZone.RightLeg : SurgeryZone.LeftLeg;
            var count = (_injuries!.GetValueOrDefault(other) & SurgeryInjury.Missing) != 0 ? 2 : 1;
            return _loc.GetString("orbitra-analyzer-anatomy-legs-missing",
                ("percent", Percent(1f - OrbitraSurgeryAnatomySystem.MissingLegSpeed(count))));
        }
        if (_effects.Trauma is not { } profile)
            return null;
        var splinted = (injuries & SurgeryInjury.Splinted) != 0;
        var seconds = Math.Round(profile.TickSeconds * Math.Max(0.01f, _effects.TickMultiplier), 2);
        return finding switch
        {
            SurgeryInjury.Fracture when leg => _loc.GetString("orbitra-analyzer-anatomy-leg-fracture",
                ("percent", Percent(1f - (splinted ? profile.SplintedLegSpeed : profile.FracturedLegSpeed)))),
            SurgeryInjury.Fracture when arm => _loc.GetString("orbitra-analyzer-anatomy-arm-fracture",
                ("percent", Percent((splinted ? profile.SplintedArmDelay : profile.FracturedArmDelay) - 1f))),
            SurgeryInjury.InternalBleeding => _loc.GetString("orbitra-analyzer-anatomy-internal-bleeding",
                ("amount", ((injuries & SurgeryInjury.Bandaged) != 0 ? profile.BandagedBloodLoss : profile.BloodLoss).Double()),
                ("seconds", seconds)),
            SurgeryInjury.Shrapnel => _loc.GetString("orbitra-analyzer-anatomy-shrapnel",
                ("damage", profile.FragmentDamage.GetTotal().Double()), ("seconds", seconds)),
            _ => null,
        };
    }

    private static double Percent(float fraction) => Math.Round(fraction * 100, 2);

    private string? OrganEffect(SurgeryOrgan organ, SurgeryOrganCondition condition)
    {
        if (condition == SurgeryOrganCondition.Healthy || _effects.Organs is not { } patient)
            return null;
        var damaged = condition == SurgeryOrganCondition.Damaged;
        return organ switch
        {
            SurgeryOrgan.Heart when damaged => _loc.GetString("orbitra-analyzer-anatomy-heart-damaged",
                ("percent", Percent(patient.HeartRecovery))),
            SurgeryOrgan.Heart => _loc.GetString("orbitra-analyzer-anatomy-heart-failure", ("amount", Math.Round(patient.HeartLoss, 2))),
            SurgeryOrgan.Lungs when damaged => _loc.GetString("orbitra-analyzer-anatomy-lungs-damaged",
                ("percent", Percent(patient.BreathFraction))),
            SurgeryOrgan.Lungs => _loc.GetString("orbitra-analyzer-anatomy-lungs-failure"),
            SurgeryOrgan.Liver when damaged && patient.LiverInterval > 0f => _loc.GetString("orbitra-analyzer-anatomy-liver-damaged",
                ("percent", Percent(1f / Math.Max(1f, patient.LiverInterval)))),
            SurgeryOrgan.Liver => _loc.GetString("orbitra-analyzer-anatomy-liver-failure"),
            _ => null,
        };
    }
}
