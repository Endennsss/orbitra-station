using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Orbitra.Graphics;

[GenerateTypedNameReferences]
public sealed partial class OrbitraBloomTuning : BoxContainer
{
    public OrbitraBloomTuning()
    {
        RobustXamlLoader.Load(this);
        ExpandButton.OnToggled += args => SetExpanded(args.Pressed);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        SetExpanded(false);
    }

    private void SetExpanded(bool expanded)
    {
        ExpandButton.Pressed = expanded;
        Settings.Visible = expanded;
        Chevron.Icon = expanded ? "chevron_down" : "chevron_right";
    }
}
