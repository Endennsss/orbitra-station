/// <summary>A colony dashboard with stable specimen selection and an independent breed reference.</summary>
[GenerateTypedNameReferences]
public sealed partial class OrbitraXenobiologyWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IEntityManager _entity = default!;
    private readonly SpriteSystem _sprite;
    private readonly Dictionary<NetEntity, OrbitraXenobiologySpecimen> _specimens = new();
    private readonly Dictionary<NetEntity, OrbitraXenobiologySpecimenButton> _rows = new();
    private readonly Dictionary<string, (Label Label, ProgressBar Bar)> _meters = new();
    private readonly Dictionary<string, Label> _genes = new();
    private readonly Dictionary<string, Button> _breedButtons = new();
    private readonly List<OrbitraXenobiologyBreedPrototype> _breeds;
    private readonly List<NetEntity> _visibleSpecimens = new();
    private NetEntity? _selectedSpecimen;
    private string? _selectedBreed;
    private Vector2 _lastViewport;
    private bool _catalogVisible;
    private bool _showColonyDetails;
    private bool _showCatalogDetails;
    private bool _initialized;
    private bool _powered;
    private int _filter;
    private int _catalogTier = -1;

    /// <summary>The selected specimen identity, retained across refreshes and row reordering.</summary>
    public NetEntity? SelectedSpecimen => _selectedSpecimen;
    /// <summary>The currently selected catalog lineage.</summary>
    public string? SelectedBreed => _selectedBreed;
    /// <summary>Specimens matching the current local search and filter.</summary>
    public IReadOnlyList<NetEntity> VisibleSpecimenIds => _visibleSpecimens;

    public OrbitraXenobiologyWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entity.System<SpriteSystem>();
        _breeds = _prototype.EnumeratePrototypes<OrbitraXenobiologyBreedPrototype>()
            .OrderBy(breed => breed.Tier).ThenBy(breed => _loc.GetString(breed.Name)).ToList();
        foreach (var key in new[] { "growth", "hunger", "biomass" })
            AddMeter(key);
        foreach (var key in new[] { "mutation", "offspring", "yield", "rate", "docility", "tolerance" })
            AddGene(key);
        var filters = new[] { "all", "baby", "adult", "attention" };
        for (var i = 0; i < filters.Length; i++)
            SpecimenFilter.AddItem(_loc.GetString("orbitra-xeno-filter-" + filters[i]), i);
        OrbitraOptionButton.BindSelection(SpecimenFilter, args =>
        {
            _filter = args.Id;
            SpecimenFilter.SelectId(args.Id);
            ApplySpecimenFilter();
        });
        SpecimenSearch.OnTextChanged += _ => ApplySpecimenFilter();
        CatalogSearch.OnTextChanged += _ => ApplyCatalogFilter();
        CatalogTierFilter.AddItem(_loc.GetString("orbitra-xeno-tier-all"), -1);
        foreach (var tier in _breeds.Select(breed => breed.Tier).Distinct())
            CatalogTierFilter.AddItem(_loc.GetString("orbitra-xeno-tier", ("tier", tier)), tier);
        OrbitraOptionButton.BindSelection(CatalogTierFilter, args =>
        {
            _catalogTier = args.Id;
            CatalogTierFilter.SelectId(args.Id);
            ApplyCatalogFilter();
        });
        CatalogCareButton.OnPressed += _ => ShowCatalogRecipes(false);
        CatalogRecipesButton.OnPressed += _ => ShowCatalogRecipes(true);
        SpecimensButton.OnPressed += _ => ShowCatalog(false);
        CatalogButton.OnPressed += _ => ShowCatalog(true);
        SpecimenBack.OnPressed += _ => { _showColonyDetails = false; UpdateAdaptiveLayout(); };
        CatalogBack.OnPressed += _ => { _showCatalogDetails = false; UpdateAdaptiveLayout(); };
        OpenSelectedBreed.OnPressed += _ =>
        {
            if (_selectedSpecimen is { } id && _specimens.TryGetValue(id, out var specimen))
            {
                ShowCatalog(true);
                SelectBreed(specimen.Breed);
            }
        };
        GuideButton.OnToggled += args => ShowGuide(args.Pressed);
        BuildCatalog();
        _initialized = true;
        FitToViewport(UserInterfaceManager.WindowRoot.Size);
        ApplySpecimenFilter();
        if (_breeds.Count > 0)
            SelectBreed(_breeds[0].ID, false);
        OrbitraEntryWindow.Attach(this);
        OrbitraEditorStyles.Apply(this);
    }

    /// <summary>Fits the window to the logical viewport, including enlarged interface scales.</summary>
    public void FitToViewport(Vector2 viewport)
    {
        if (viewport.X <= 0 || viewport.Y <= 0)
            return;
        _lastViewport = UserInterfaceManager.WindowRoot.Size;
        var available = OrbitraXenobiologyPresentation.Available(viewport);
        MinSize = Vector2.Min(new Vector2(640, 400), available);
        MaxSize = available;
        SetSize = Vector2.Min(new Vector2(1000, 650), available);
        UpdateAdaptiveLayout();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var viewport = UserInterfaceManager.WindowRoot.Size;
        if (viewport != _lastViewport)
            FitToViewport(viewport);
    }

    protected override void Resized()
    {
        base.Resized();
        if (_initialized)
            UpdateAdaptiveLayout();
    }

    private void UpdateAdaptiveLayout()
    {
        var narrow = (Size.X > 0 ? Size.X : SetSize.X) < 760;
        ListPanel.Visible = !narrow || !_showColonyDetails;
        SpecimenPanel.Visible = !narrow || _showColonyDetails;
        CatalogListPanel.Visible = !narrow || !_showCatalogDetails;
        CatalogDetailsPanel.Visible = !narrow || _showCatalogDetails;
        ListPanel.SetWidth = narrow ? float.NaN : 290;
        ListPanel.HorizontalExpand = narrow;
        CatalogListPanel.SetWidth = narrow ? float.NaN : 290;
        CatalogListPanel.HorizontalExpand = narrow;
        SpecimenBack.Visible = narrow;
        CatalogBack.Visible = narrow;
    }

    private void ShowCatalog(bool show)
    {
        _catalogVisible = show;
        Status.Visible = !show;
        GuideButton.Pressed = false;
        ShowGuide(false);
        CatalogButton.Pressed = show;
        SpecimensButton.Pressed = !show;
        UpdateSummary();
        UpdateAdaptiveLayout();
    }

    private void ShowGuide(bool show)
    {
        HelpPanel.Visible = show;
        CatalogContent.Visible = !show && _catalogVisible;
        ColonyContent.Visible = !show && !_catalogVisible;
    }

    /// <summary>Refreshes measurements without replacing rows, selection or the catalog scroll position.</summary>
    public void UpdateState(OrbitraXenobiologyBoundUserInterfaceState state)
    {
        _powered = state.Powered;
        _specimens.Clear();
        foreach (var specimen in state.Specimens)
        {
            if (!_prototype.TryIndex<OrbitraXenobiologyBreedPrototype>(specimen.Breed, out var breed))
                continue;
            _specimens[specimen.Entity] = specimen;
            if (!_rows.TryGetValue(specimen.Entity, out var row))
            {
                var id = specimen.Entity;
                row = new OrbitraXenobiologySpecimenButton();
                row.OnPressed += _ => SelectSpecimen(id);
                _rows.Add(id, row);
                SpecimenList.AddChild(row);
            }
            row.Update(specimen, breed, _loc, _sprite);
        }
        foreach (var id in _rows.Keys.Where(id => !_specimens.ContainsKey(id)).ToArray())
        {
            SpecimenList.RemoveChild(_rows[id]);
            _rows.Remove(id);
        }
        var position = 0;
        foreach (var id in _rows.Keys.OrderBy(id => id.Id))
            _rows[id].SetPositionInParent(position++);
        Status.Text = _loc.GetString(state.Powered ? "orbitra-xeno-live-count" : "orbitra-xeno-unpowered",
            ("count", _specimens.Count), ("range", OrbitraXenobiologyPresentation.Number(state.Range)));
        Status.ToolTip = Status.Text;
        Status.FontColorOverride = state.Powered ? Palettes.Green.Text : Palettes.Amber.Text;
        ApplySpecimenFilter();
    }

    /// <summary>Selects a visible specimen without sending any remote game action.</summary>
    public bool SelectSpecimen(NetEntity id)
    {
        if (!_specimens.ContainsKey(id) || !_rows[id].Visible)
            return false;
        if (_selectedSpecimen != id)
            SpecimenDetailsScroll.SetScrollValue(Vector2.Zero);
        _selectedSpecimen = id;
        _showColonyDetails = true;
        UpdateSelection();
        UpdateAdaptiveLayout();
        return true;
    }

    private void ApplySpecimenFilter()
    {
        _visibleSpecimens.Clear();
        foreach (var (id, row) in _rows.OrderBy(pair => pair.Key.Id))
        {
            var specimen = _specimens[id];
            var breed = _prototype.Index<OrbitraXenobiologyBreedPrototype>(specimen.Breed);
            var matches = _filter switch
            {
                1 => !specimen.Adult && !specimen.Dead,
                2 => specimen.Adult && !specimen.Dead,
                3 => OrbitraXenobiologyPresentation.NeedsAttention(specimen),
                _ => true,
            };
            var search = SpecimenSearch.Text.Trim();
            row.Visible = matches && (search.Length == 0 || specimen.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase) ||
                specimen.Identifier.Contains(search, StringComparison.CurrentCultureIgnoreCase) ||
                _loc.GetString(breed.Name).Contains(search, StringComparison.CurrentCultureIgnoreCase));
            if (row.Visible)
                _visibleSpecimens.Add(id);
        }
        if (_selectedSpecimen is { } missing && !_specimens.ContainsKey(missing))
            _selectedSpecimen = null;
        if (_visibleSpecimens.Count > 0 && (_selectedSpecimen is not { } selected || !_visibleSpecimens.Contains(selected)))
            _selectedSpecimen = _visibleSpecimens[0];
        ColonyEmpty.Visible = _visibleSpecimens.Count == 0;
        ColonyEmpty.Text = _loc.GetString(!_powered ? "orbitra-xeno-unpowered" : _specimens.Count == 0
            ? "orbitra-xeno-no-specimens" : "orbitra-xeno-no-matching-specimens");
        UpdateSelection();
        UpdateSummary();
    }

    private void UpdateSelection()
    {
        foreach (var (rowId, row) in _rows)
            row.Pressed = rowId == _selectedSpecimen;
        var present = _selectedSpecimen is { } selected && _visibleSpecimens.Contains(selected);
        SelectHint.Visible = !present;
        SpecimenDetails.Visible = present;
        if (!present || _selectedSpecimen is not { } id)
        {
            SelectHint.SetMessage(_loc.GetString(!_powered ? "orbitra-xeno-offline-hint" :
                _specimens.Count == 0 ? "orbitra-xeno-colony-start-hint" : "orbitra-xeno-search-hint"));
            Portrait.SetPrototype(null);
            return;
        }
        var specimen = _specimens[id];
        var breed = _prototype.Index<OrbitraXenobiologyBreedPrototype>(specimen.Breed);
        SelectedName.Text = OrbitraXenobiologyPresentation.Name(specimen, _loc.GetString(breed.Name), _loc);
        SelectedName.ToolTip = SelectedName.Text;
        SelectedBreedLabel.Text = _loc.GetString("orbitra-xeno-selected-breed", ("breed", _loc.GetString(breed.Name)), ("generation", specimen.Generation));
        SelectedBreedLabel.ToolTip = SelectedBreedLabel.Text;
        SelectedStatus.Text = OrbitraXenobiologyPresentation.Status(specimen, _loc);
        SelectedStatus.ToolTip = SelectedStatus.Text;
        SelectedStatus.FontColorOverride = OrbitraXenobiologyPresentation.StatusColor(specimen);
        OrbitraXenobiologyPresentation.SetPortrait(Portrait, _entity, breed, specimen);
        SetMeter("growth", specimen.Adult ? 1 : specimen.Growth,
            _loc.GetString(specimen.Adult ? "orbitra-xeno-growth-adult" : "orbitra-xeno-growth-value", ("amount", MathF.Round(specimen.Growth * 100))), OrbitraPalettes.Primary.Element);
        SetMeter("hunger", specimen.Hunger / 100,
            _loc.GetString("orbitra-xeno-hunger-value", ("amount", MathF.Round(specimen.Hunger))),
            Palettes.Status.GetStatusColor(OrbitraXenobiologyPresentation.Unit(specimen.Hunger / 100)));
        var required = specimen.Adult ? specimen.DivisionBiomass : specimen.GrowthBiomass;
        SetMeter("biomass", required > 0 ? specimen.Biomass / required : 0,
            _loc.GetString("orbitra-xeno-biomass-value", ("amount", OrbitraXenobiologyPresentation.Number(specimen.Biomass)), ("required", required)), OrbitraPalettes.Primary.Element);
        Temperature.Text = _loc.GetString("orbitra-xeno-temperature-value", ("temperature", OrbitraXenobiologyPresentation.Number(specimen.Temperature - 273.15f)));
        Temperature.FontColorOverride = specimen.Temperature < specimen.MinimumTemperature || specimen.Temperature > specimen.MaximumTemperature
            ? Palettes.Amber.Text : Palettes.Green.Text;
        TemperatureRange.Text = _loc.GetString("orbitra-xeno-temperature-range", ("minimum", OrbitraXenobiologyPresentation.Number(specimen.MinimumTemperature - 273.15f)),
            ("maximum", OrbitraXenobiologyPresentation.Number(specimen.MaximumTemperature - 273.15f)));
        Temperature.ToolTip = Temperature.Text;
        TemperatureRange.ToolTip = TemperatureRange.Text;
        SetGene("mutation", _loc.GetString("orbitra-xeno-percent", ("amount", MathF.Round(specimen.MutationChance * 100))));
        SetGene("offspring", specimen.Offspring.ToString());
        SetGene("yield", specimen.ExtractYield.ToString());
        SetGene("rate", _loc.GetString("orbitra-xeno-multiplier", ("amount", OrbitraXenobiologyPresentation.Number(specimen.GrowthRate))));
        SetGene("docility", _loc.GetString("orbitra-xeno-percent", ("amount", MathF.Round(specimen.Docility * 100))));
        SetGene("tolerance", _loc.GetString("orbitra-xeno-kelvin", ("amount", OrbitraXenobiologyPresentation.Number(specimen.ThermalTolerance))));
    }

    private void UpdateSummary()
    {
        Summary.Text = _catalogVisible ? _loc.GetString("orbitra-xeno-catalog-count", ("count", _breedButtons.Count(pair => pair.Value.Visible))) :
            _loc.GetString("orbitra-xeno-colony-summary", ("visible", _visibleSpecimens.Count), ("total", _specimens.Count),
                ("attention", _specimens.Values.Count(OrbitraXenobiologyPresentation.NeedsAttention)));
        Summary.ToolTip = Summary.Text;
    }

    private void AddMeter(string key)
    {
        var label = new Label { ClipText = true };
        var bar = new ProgressBar { MinValue = 0, MaxValue = 1, MinHeight = 10, HorizontalExpand = true };
        OrbitraXenobiologyPresentation.StyleMeter(bar);
        Vitals.AddChild(label);
        Vitals.AddChild(bar);
        _meters.Add(key, (label, bar));
    }

    private void SetMeter(string key, float value, string text, Color color)
    {
        var meter = _meters[key];
        meter.Label.Text = text;
        meter.Label.ToolTip = text;
        meter.Bar.Value = OrbitraXenobiologyPresentation.Unit(value);
        meter.Bar.ForegroundStyleBoxOverride = OrbitraXenobiologyPresentation.MeterFill(color);
    }

    private void AddGene(string key)
    {
        var row = new BoxContainer { SeparationOverride = 8, HorizontalExpand = true };
        var caption = _loc.GetString("orbitra-xeno-gene-" + key);
        row.AddChild(new Label { Text = caption, ToolTip = caption, ClipText = true, HorizontalExpand = true, StyleClasses = { StyleClass.LabelSubText } });
        var amount = new Label();
        row.AddChild(amount);
        Genetics.AddChild(row);
        _genes.Add(key, amount);
    }

    private void SetGene(string key, string amount) => _genes[key].Text = amount;
}
