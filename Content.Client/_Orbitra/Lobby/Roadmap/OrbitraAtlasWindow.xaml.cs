using System.Linq;
using System.Numerics;
using Content.Client._Orbitra.UserInterface;
using Content.Client.UserInterface.Controls;
using Content.Shared._Orbitra.Roadmap;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Orbitra.Lobby.Roadmap;

/// <summary>Карточка выбранного созвездия закрепляется справа или встраивается в маршрут под звездой.</summary>
[GenerateTypedNameReferences]
public sealed partial class OrbitraAtlasWindow : FancyWindow
{
    private AtlasEntry[] _entries = [];
    private readonly List<OrbitraAtlasRow> _rows = [];
    private int _selected = -1;
    private bool _canEdit;

    public event Action<Guid?>? EditRequested;

    public OrbitraAtlasWindow()
    {
        RobustXamlLoader.Load(this);
        CreateButton.OnPressed += _ => EditRequested?.Invoke(null);
        EditButton.OnPressed += _ =>
        {
            if (_canEdit && _selected >= 0)
                EditRequested?.Invoke(_entries[_selected].Id);
        };
        Columns.OnResized += PlaceDetail;
        Display(new OrbitraRoadmapState { Loading = true });
    }

    public void Display(OrbitraRoadmapState state)
    {
        var selectedId = _selected >= 0 ? _entries[_selected].Id : (Guid?) null;
        var restoreFocus = _rows.Any(row => row.Button.HasKeyboardFocus());
        _entries = state.Entries;
        _canEdit = state.CanEdit;
        _selected = -1;
        Detail.Orphan();
        Route.RemoveAllChildren();
        _rows.Clear();
        for (var i = 0; i < _entries.Length; i++)
        {
            var index = i;
            var entry = _entries[i];
            var row = new OrbitraAtlasRow(entry, i, _entries.Length);
            row.Button.OnPressed += _ => Select(index, true);
            Route.AddChild(row);
            _rows.Add(row);
            if (entry.Id == selectedId)
                _selected = i;
        }

        CreateButton.Visible = state.CanEdit && !state.Loading;
        ChartScroll.Visible = _entries.Length > 0;
        ChartCount.Visible = ChartScroll.Visible;
        Empty.Visible = !ChartScroll.Visible;
        var hasNotice = !string.IsNullOrEmpty(state.Notice);
        Notice.Visible = hasNotice && !Empty.Visible;
        if (hasNotice)
            Notice.SetMessage(Loc.GetString(state.Notice!));

        if (Empty.Visible)
        {
            Dock.Visible = false;
            EmptyTitle.Visible = state.Loading;
            EmptyTitle.Text = Loc.GetString("orbitra-atlas-loading");
            EmptyMessage.Visible = !state.Loading;
            EmptyMessage.SetMessage(Loc.GetString(hasNotice ? state.Notice! : "orbitra-atlas-empty"));
            return;
        }

        ChartCount.Text = Loc.GetString("orbitra-atlas-count",
            ("done", _entries.Count(entry => entry.Content.Status == AtlasStatus.Done)), ("total", _entries.Length));
        Select(Math.Max(_selected, 0), false);
        if (restoreFocus)
            OrbitraKeyboardNavigation.Focus(_rows[_selected].Button);
    }

    private void Select(int index, bool reveal)
    {
        if (_selected >= 0)
            _rows[_selected].Selected = false;
        _selected = index;
        var row = _rows[index];
        row.Selected = true;
        var entry = _entries[index];
        var content = entry.Content;
        DetailTitle.SetMessage(content.Title);
        Description.Visible = content.Description.Length > 0;
        Description.SetMessage(content.Description);
        DetailMarker.Status = content.Status;
        DetailStatus.Text = OrbitraAtlasArt.StatusText(content.Status);
        DetailStatus.FontColorOverride = OrbitraAtlasArt.Tint(content.Status);
        EditButton.Visible = _canEdit;
        Publication.Visible = _canEdit && (!entry.Published || entry.Pending);
        if (Publication.Visible)
            Publication.SetMessage(Loc.GetString(entry.Published ? "orbitra-atlas-pending" : "orbitra-atlas-draft"));

        Tasks.RemoveAllChildren();
        TaskSection.Visible = content.Tasks.Length > 0;
        TaskCount.Text = Loc.GetString("orbitra-atlas-tasks",
            ("done", content.Tasks.Count(task => task.Status == AtlasStatus.Done)), ("total", content.Tasks.Length));
        foreach (var task in content.Tasks)
        {
            var line = new BoxContainer { SeparationOverride = 8 };
            line.AddChild(new OrbitraAtlasMarker { Status = task.Status, SetSize = new Vector2(14), Margin = new Thickness(0, 2, 0, 0),
                VerticalAlignment = VAlignment.Top });
            var copy = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 0 };
            var title = new RichTextLabel();
            title.SetMessage(task.Title);
            copy.AddChild(title);
            copy.AddChild(new Label { Text = task.Status == AtlasStatus.Done ? Loc.GetString("orbitra-atlas-task-status-done") : OrbitraAtlasArt.StatusText(task.Status), StyleClasses = { "OrbitraLobbyMuted" } });
            line.AddChild(copy);
            Tasks.AddChild(line);
        }

        PlaceDetail();
        Dock.SetScrollValue(Vector2.Zero);
        if (reveal && !Dock.Visible)
        {
            // По сворачивании предыдущей карточки координаты звезды могут сдвинуться на несколько экранов.
            UserInterfaceManager.DeferAction(() =>
            {
                if (!IsOpen || _selected != index || Dock.Visible || row.Parent != Route)
                    return;
                var y = ChartScroll.GetScrollValue().Y + row.GlobalPosition.Y - ChartScroll.GlobalPosition.Y;
                ChartScroll.SetScrollValue(new Vector2(0, y));
            });
        }
    }

    private void PlaceDetail()
    {
        if (_selected < 0)
            return;
        var wide = Columns.Width >= 680;
        Dock.Visible = wide;
        if (wide)
            Dock.SetWidth = Math.Clamp(Columns.Width * 0.40f, 280, 420);
        Control parent = wide ? Dock : Route;
        if (Detail.Parent != parent)
        {
            Detail.Orphan();
            parent.AddChild(Detail);
        }
        if (!wide && Detail.GetPositionInParent() != _selected + 1)
        {
            Detail.SetPositionInParent(_selected + 1);
            Route.InvalidateArrange();
        }
    }
}
