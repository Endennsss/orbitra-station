using System.Linq;
using Content.Client._Orbitra.UserInterface;
using Content.Client.UserInterface.Controls;
using Content.Shared._Orbitra.Roadmap;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Orbitra.Lobby.Roadmap;

/// <summary>Редактирует одну запись Атласа, сохраняя введённый текст при конфликте версий.</summary>
[GenerateTypedNameReferences]
public sealed partial class OrbitraAtlasEditorWindow : FancyWindow
{
    [Dependency] private ILocalizationManager _loc = default!;

    private readonly Guid _id;
    private AtlasContent _baseline;
    private AtlasEntry? _latest;
    private AtlasChange? _pending;
    private int _revision;
    private int _position = -1;
    private int _entryCount;
    private bool _available;

    /// <summary>Передаёт команду с версией, на которой основаны локальные правки.</summary>
    public event Action<AtlasChange>? Submitted;

    public OrbitraAtlasEditorWindow(Guid id, AtlasEntry? initial)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _id = id;
        _latest = initial;
        _revision = initial?.Revision ?? 0;
        _baseline = initial?.Content ?? new AtlasContent("", "", AtlasStatus.Planned, []);

        EntryTitle.IsValid = text => text.Length <= AtlasLimits.Title;
        EntryDescription.OnTextChanged += _ => UpdateLength();
        SetupStatus(EntryStatus);
        AddTask.OnPressed += _ =>
        {
            var row = AppendTask(new AtlasTask("", AtlasStatus.Planned));
            UpdateTaskButtons();
            row.TitleEdit.GrabKeyboardFocus();
        };
        KeepForm.OnPressed += _ => AcceptLatest(keepForm: true);
        LoadLatest.OnPressed += _ => AcceptLatest(keepForm: false);
        Save.OnPressed += _ => Submit(AtlasAction.Save);
        Publish.OnPressed += _ => Submit(AtlasAction.Publish);
        Unpublish.OnPressed += _ => Submit(AtlasAction.Unpublish);
        EntryUp.OnPressed += _ => Submit(AtlasAction.MoveUp);
        EntryDown.OnPressed += _ => Submit(AtlasAction.MoveDown);
        FillForm(_baseline);
        UpdateActions();
    }

    /// <summary>Обрабатывает свой ответ и обновления других редакторов, пока окно открыто.</summary>
    public void Display(OrbitraRoadmapState state)
    {
        _available = state.CanEdit && !state.Loading;
        if (_available)
        {
            _position = Array.FindIndex(state.Entries, entry => entry.Id == _id);
            _entryCount = state.Entries.Length;
            if (_position >= 0 && state.Entries[_position].Revision >= (_latest?.Revision ?? 0))
                _latest = state.Entries[_position];
        }

        if (_pending is { } request && state.ReplyTo == request.RequestId)
        {
            _pending = null;
            if (state.Success)
            {
                // Успешная запись увеличивает ревизию ровно на один. Снимок может уже содержать следующую правку.
                _revision = request.Revision + 1;
                _baseline = request.Content ?? _baseline;
            }
            var notice = state.Success ? request.Action switch
            {
                AtlasAction.Publish => "orbitra-atlas-editor-published",
                AtlasAction.Unpublish => "orbitra-atlas-editor-unpublished",
                AtlasAction.Save => "orbitra-atlas-editor-saved",
                _ => "orbitra-atlas-editor-moved",
            } : state.Notice ?? "orbitra-atlas-invalid";
            SetFeedback(_loc.GetString(notice));
        }

        if (_available && _pending == null && _latest != null && _latest.Revision > _revision && FormMatchesBaseline())
            AcceptLatest(keepForm: false);

        UpdateActions();
    }

    private bool FormMatchesBaseline()
    {
        if (EntryDescription.TextLength != _baseline.Description.Length)
            return false;
        var form = ReadForm();
        return form.Title == _baseline.Title && form.Description == _baseline.Description &&
            form.Status == _baseline.Status && form.Tasks.SequenceEqual(_baseline.Tasks);
    }

    private void AcceptLatest(bool keepForm)
    {
        if (_latest == null)
            return;

        _revision = _latest.Revision;
        _baseline = _latest.Content;
        if (!keepForm)
            FillForm(_baseline);
        SetFeedback(null);
        UpdateActions();
    }

    private void FillForm(AtlasContent content)
    {
        EntryTitle.Text = content.Title;
        EntryTitle.CursorPosition = 0;
        EntryDescription.TextRope = new Rope.Leaf(content.Description);
        EntryDescription.CursorPosition = default;
        EntryStatus.SelectId((int) content.Status);
        TaskList.RemoveAllChildren();
        foreach (var task in content.Tasks)
            AppendTask(task);
        UpdateTaskButtons();
        UpdateLength();
    }

    private AtlasContent ReadForm()
    {
        var tasks = new AtlasTask[TaskList.ChildCount];
        for (var i = 0; i < tasks.Length; i++)
        {
            var row = (TaskRow) TaskList.GetChild(i);
            tasks[i] = new AtlasTask(row.TitleEdit.Text, (AtlasStatus) row.Status.SelectedId);
        }
        return new AtlasContent(EntryTitle.Text, Rope.Collapse(EntryDescription.TextRope), (AtlasStatus) EntryStatus.SelectedId, tasks);
    }

    private void Submit(AtlasAction action)
    {
        if (!_available || _pending != null || ConflictPanel.Visible)
            return;

        AtlasContent? content = null;
        if (action is AtlasAction.Save or AtlasAction.Publish)
        {
            if (EntryDescription.TextLength <= AtlasLimits.Description)
                content = ReadForm();
            if (!AtlasLimits.Valid(content))
            {
                SetFeedback(_loc.GetString("orbitra-atlas-editor-invalid", ("max", AtlasLimits.Description)));
                return;
            }
        }
        var request = new AtlasChange
        {
            Id = _id,
            Revision = _revision,
            Action = action,
            Content = content,
            RequestId = Guid.NewGuid(),
        };
        _pending = request;
        SetFeedback(_loc.GetString("orbitra-atlas-editor-waiting"));
        UpdateActions();
        Submitted?.Invoke(request);
    }

    private void UpdateActions()
    {
        var conflict = _pending == null && _latest != null && _latest.Revision > _revision;
        var disabled = !_available || _pending != null || conflict;
        ConflictPanel.Visible = conflict;
        Save.Disabled = Publish.Disabled = disabled;
        EntryControls.Visible = _latest != null;
        EntryUp.Disabled = disabled || _position <= 0;
        EntryDown.Disabled = disabled || _position < 0 || _position >= _entryCount - 1;
        Unpublish.Visible = _latest?.Published == true;
        if (disabled || !Unpublish.IsConfirming)
            Unpublish.Disabled = disabled;
    }

    private void SetFeedback(string? message)
    {
        Feedback.Text = message;
        Feedback.Visible = !string.IsNullOrEmpty(message);
    }

    private void UpdateLength()
    {
        DescriptionLength.Text = _loc.GetString("orbitra-atlas-editor-length",
            ("count", EntryDescription.TextLength), ("max", AtlasLimits.Description));
    }

    private void SetupStatus(OrbitraOptionButton option, bool task = false)
    {
        option.MinWidth = 160;
        option.PrefixMargin = false;
        option.AddItem(_loc.GetString("orbitra-atlas-status-planned"), (int) AtlasStatus.Planned);
        option.AddItem(_loc.GetString("orbitra-atlas-status-active"), (int) AtlasStatus.Active);
        option.AddItem(_loc.GetString(task ? "orbitra-atlas-task-status-done" : "orbitra-atlas-status-done"), (int) AtlasStatus.Done);
        OrbitraOptionButton.BindSelection(option, args => option.SelectId(args.Id));
    }

    private TaskRow AppendTask(AtlasTask task)
    {
        var row = new TaskRow();
        row.TitleEdit.IsValid = text => text.Length <= AtlasLimits.TaskTitle;
        row.TitleEdit.PlaceHolder = _loc.GetString("orbitra-atlas-editor-task-name");
        row.TitleEdit.Text = task.Title;
        row.TitleEdit.CursorPosition = 0;
        SetupStatus(row.Status, task: true);
        row.Status.SelectId((int) task.Status);
        row.Up = AddTaskButton(row, "chevron_up", "orbitra-atlas-editor-task-up", () => MoveTask(row, -1));
        row.Down = AddTaskButton(row, "chevron_down", "orbitra-atlas-editor-task-down", () => MoveTask(row, 1));
        AddTaskButton(row, "trash", "orbitra-atlas-editor-task-remove", () =>
        {
            TaskList.RemoveChild(row);
            UpdateTaskButtons();
        });
        TaskList.AddChild(row);
        return row;
    }

    private OrbitraButton AddTaskButton(TaskRow row, string icon, string tooltip, Action pressed)
    {
        var button = new OrbitraButton { MinWidth = OrbitraUiMetrics.ElementHeight, ToolTip = _loc.GetString(tooltip) };
        button.AddChild(new OrbitraIcon { Icon = icon });
        button.OnPressed += _ => pressed();
        row.Actions.AddChild(button);
        return button;
    }

    private void MoveTask(TaskRow row, int offset)
    {
        row.SetPositionInParent(row.GetPositionInParent() + offset);
        TaskList.InvalidateArrange();
        UpdateTaskButtons();
    }

    private void UpdateTaskButtons()
    {
        for (var i = 0; i < TaskList.ChildCount; i++)
        {
            var row = (TaskRow) TaskList.GetChild(i);
            row.Up.Disabled = i == 0;
            row.Down.Disabled = i == TaskList.ChildCount - 1;
        }
        AddTask.Disabled = TaskList.ChildCount >= AtlasLimits.Tasks;
    }

    private sealed class TaskRow : BoxContainer
    {
        public readonly LineEdit TitleEdit = new() { HorizontalExpand = true };
        public readonly OrbitraOptionButton Status = new();
        public readonly WrapContainer Actions = new() { SeparationOverride = 4, CrossSeparationOverride = 4 };
        public OrbitraButton Up = default!;
        public OrbitraButton Down = default!;

        public TaskRow()
        {
            var fields = new OrbitraAdaptiveRow { Breakpoint = 460, SeparationOverride = 4, HorizontalExpand = true };
            AddChild(fields);
            fields.AddChild(TitleEdit);
            fields.AddChild(Actions);
            Actions.AddChild(Status);
        }
    }
}
