using System.Linq;
using Content.Client._Orbitra.UserInterface;
using Content.Client.UserInterface.Controls;
using Content.Shared._Orbitra.Ghost;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Orbitra.Ghost.Skins;

/// <summary>A prototype-driven cosmetic selector owned by the ghost HUD.</summary>
[GenerateTypedNameReferences]
public sealed partial class OrbitraGhostSkinWindow : FancyWindow
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    private readonly OrbitraGhostSkinSystem _skins;
    private readonly SpriteSystem _sprite;
    private readonly OrbitraGhostSkinPrototype[] _choices;

    public OrbitraGhostSkinWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _skins = _entity.System<OrbitraGhostSkinSystem>();
        _sprite = _entity.System<SpriteSystem>();
        _choices = _prototype.EnumeratePrototypes<OrbitraGhostSkinPrototype>()
            .OrderBy(skin => skin.Order).ThenBy(skin => skin.ID, StringComparer.Ordinal).ToArray();
        for (var index = 0; index < _choices.Length; index++)
            SkinPicker.AddItem(Loc.GetString(_choices[index].Name), index);
        OrbitraOptionButton.BindSelection(SkinPicker, args =>
        {
            SkinPicker.SelectId(args.Id);
            UpdatePreview();
        });
        ApplyButton.OnPressed += _ =>
        {
            if (SkinPicker.SelectedId >= 0 && SkinPicker.SelectedId < _choices.Length)
                _skins.RequestSkin(_choices[SkinPicker.SelectedId].ID);
        };
        OnOpen += OnOpened;
        OnClose += OnClosed;
        OrbitraEntryWindow.Attach(this);
        OrbitraEditorStyles.Apply(this);
    }

    private void OnOpened()
    {
        _skins.SkinChanged -= Synchronize;
        _skins.SkinChanged += Synchronize;
        Synchronize();
    }

    private void OnClosed() => _skins.SkinChanged -= Synchronize;

    private void Synchronize()
    {
        var index = Array.FindIndex(_choices, choice => choice.ID == _skins.SelectedSkin.Id);
        if (_choices.Length > 0)
            SkinPicker.SelectId(Math.Max(0, index));
        UpdatePreview();
    }

    private void UpdatePreview()
    {
        var index = SkinPicker.SelectedId;
        if (index < 0 || index >= _choices.Length)
        {
            ApplyButton.Disabled = true;
            return;
        }
        var choice = _choices[index];
        Preview.Texture = _sprite.Frame0(choice.Icon);
        var alpha = choice.Sprite == null ? 0.53333336f :
            float.IsFinite(choice.Opacity) ? Math.Clamp(choice.Opacity, 0, 1) : 0.5f;
        Preview.Modulate = Color.White.WithAlpha(alpha);
        Description.SetMessage(Loc.GetString(choice.Description));
        var current = _prototype.Index(_skins.SelectedSkin);
        CurrentSkin.SetMessage(Loc.GetString("orbitra-ghost-skins-selected", ("name", Loc.GetString(current.Name))));
        ApplyButton.Disabled = choice.ID == current.ID;
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            OnClosed();
        base.Dispose(disposing);
    }
}
