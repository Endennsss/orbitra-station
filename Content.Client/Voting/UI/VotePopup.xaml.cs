using System;
using Content.Client.Gameplay; // Orbitra-Edit
using Content.Client.Stylesheets;
using Content.Shared.Ghost;
using Content.Shared.Ghost.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.State; // Orbitra-Edit
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Voting.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class VotePopup : Control
    {
        [Dependency] private IGameTiming _gameTiming = default!;
        [Dependency] private IVoteManager _voteManager = default!;
        [Dependency] private IEntityNetworkManager _net = default!;

        private readonly VoteManager.ActiveVote _vote;
        private readonly VoteOptionButton[] _voteButtons; // Orbitra-Edit
        private readonly NetEntity? _targetEntity;

        public VotePopup(VoteManager.ActiveVote vote)
        {
            _vote = vote;
            IoCManager.InjectDependencies(this);
            RobustXamlLoader.Load(this);

            Stylesheet = IoCManager.Resolve<IStylesheetManager>().SheetSystem;

            if (_vote.TargetEntity != null && _vote.TargetEntity != 0 &&
                IoCManager.Resolve<IStateManager>().CurrentState is GameplayState) // Orbitra-Edit - наблюдение доступно в раунде.
            {
                _targetEntity = new NetEntity(_vote.TargetEntity.Value);
                FollowVoteTarget.Visible = true;
                FollowVoteTarget.OnPressed += _ => AttemptFollowVoteEntity();
            }

            _voteButtons = new VoteOptionButton[vote.Entries.Length]; // Orbitra-Edit
            var group = new ButtonGroup();

            for (var i = 0; i < _voteButtons.Length; i++)
            {
                var button = new VoteOptionButton(group); // Orbitra-Edit
                _voteButtons[i] = button;
                VoteOptionsContainer.AddChild(button);
                var i1 = i;
                button.OnPressed += _ => _voteManager.SendCastVote(vote.Id, i1);
            }

            ApplyOrbitraChrome(); // Orbitra-Edit - стандартный попап не должен обрезать длинные названия голосований.
        }

        public void UpdateData()
        {
            VoteTitle.SetMessage(FormattedMessage.FromUnformatted(_vote.Title));
            VoteCaller.SetMessage(Loc.GetString("ui-vote-created", ("initiator", _vote.Initiator))); // Orbitra-Edit

            for (var i = 0; i < _voteButtons.Length; i++)
            {
                var entry = _vote.Entries[i];
                // Orbitra edit start - длинные варианты переносятся внутри кнопки.
                var caption = _vote.DisplayVotes
                    ? Loc.GetString("ui-vote-button", ("text", entry.Text), ("votes", entry.Votes))
                    : Loc.GetString("ui-vote-button-no-votes", ("text", entry.Text));
                _voteButtons[i].SetCaption(caption);
                // Orbitra edit end

                if (_vote.OurVote == i)
                    _voteButtons[i].Pressed = true;
            }
        }

        private void AttemptFollowVoteEntity()
        {
            if (_targetEntity != null)
            {
                var msg = new GhostWarpToTargetRequestEvent(_targetEntity.Value);
                _net.SendSystemNetworkMessage(msg);
            }
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            // Logger.Debug($"{_gameTiming.ServerTime}, {_vote.StartTime}, {_vote.EndTime}");

            var curTime = _gameTiming.RealTime;
            var timeLeft = _vote.EndTime - curTime;
            if (timeLeft < TimeSpan.Zero)
                timeLeft = TimeSpan.Zero;

            // Round up a second.
            timeLeft = TimeSpan.FromSeconds(Math.Ceiling(timeLeft.TotalSeconds));

            // Orbitra edit start - окно может открыться уже после завершения голосования.
            var duration = (_vote.EndTime - _vote.StartTime).TotalSeconds;
            TimeLeftBar.Value = duration > 0
                ? (float) Math.Clamp((curTime - _vote.StartTime).TotalSeconds / duration, 0, 1)
                : 1;
            // Orbitra edit end

            TimeLeftText.Text = $"{timeLeft:m\\:ss}";
        }
    }
}
