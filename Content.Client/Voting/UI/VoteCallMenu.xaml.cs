    [GenerateTypedNameReferences]
    public sealed partial class VoteCallMenu : FancyWindow // Orbitra-Edit
    {
        [Dependency] private IClientConsoleHost _consoleHost = default!;
        [Dependency] private IVoteManager _voteManager = default!;
        [Dependency] private IGameTiming _gameTiming = default!;
        [Dependency] private IClientNetManager _netManager = default!;
        [Dependency] private IEntityManager _entityManager = default!;
        [Dependency] private IEntityNetworkManager _entNetManager = default!;
        [Dependency] private IConfigurationManager _cfg = default!;
        [Dependency] private IStateManager _state = default!;

        private readonly VotingSystem _votingSystem;
        private bool _subscribed; // Orbitra-Edit
        private string? _timeoutText; // Orbitra-Edit

        public StandardVoteType Type;

        public Dictionary<StandardVoteType, CreateVoteOption> AvailableVoteOptions = new Dictionary<StandardVoteType, CreateVoteOption>()
        {
            { StandardVoteType.Restart, new CreateVoteOption("ui-vote-type-restart", new(), false, null) },
            { StandardVoteType.Preset, new CreateVoteOption("ui-vote-type-gamemode", new(), false, null) },
            { StandardVoteType.Map, new CreateVoteOption("ui-vote-type-map", new(), false, null) },
            { StandardVoteType.Votekick, new CreateVoteOption("ui-vote-type-votekick", new(), true, 0) }
        };

        public Dictionary<string, string> VotekickReasons = new Dictionary<string, string>()
        {
            { VotekickReasonType.Raiding.ToString(), Loc.GetString("ui-vote-votekick-type-raiding") },
            { VotekickReasonType.Cheating.ToString(), Loc.GetString("ui-vote-votekick-type-cheating") },
            { VotekickReasonType.Spam.ToString(), Loc.GetString("ui-vote-votekick-type-spamming") }
        };

        public Dictionary<NetUserId, (NetEntity, string)> PlayerList = new();

        private OptionButton? _followDropdown; // Orbitra-Edit

        public bool IsAllowedVotekick = false;

        public VoteCallMenu()
        {
            IoCManager.InjectDependencies(this);
            RobustXamlLoader.Load(this);
            // Orbitra edit start - общая рамка и штатные обработчики выбора.
            OrbitraEntryWindow.Attach(this, applyEditorLayout: false);
            _votingSystem = _entityManager.System<VotingSystem>();
            VoteNotTrustedLabel.SetMessage(Loc.GetString("ui-vote-trusted-users-notice", ("timeReq", _cfg.GetCVar(CCVars.VotekickEligibleVoterDeathtime))));
            VoteFooter.ToolTip = VoteFooter.Text;
            // Orbitra edit end

            foreach (StandardVoteType voteType in Enum.GetValues<StandardVoteType>())
            {
                var option = AvailableVoteOptions[voteType];
                VoteTypeButton.AddItem(Loc.GetString(option.Name), (int)voteType);
            }

            OrbitraOptionButton.BindSelection(VoteTypeButton, VoteTypeSelected); // Orbitra-Edit
            CreateButton.OnPressed += CreatePressed;
            FollowButton.OnPressed += FollowSelected;
        }

        protected override void Opened()
        {
            base.Opened();

            // Orbitra edit start - подписываемся до сетевого запроса, один раз за открытие.
            if (_subscribed)
                return;

            _subscribed = true;
            _state.OnStateChanged += OnStateChanged;
            _voteManager.CanCallVoteChanged += CanCallVoteChanged;
            _votingSystem.VotePlayerListResponse += UpdateVotePlayerList;
            _netManager.ClientSendMessage(new MsgVoteMenu());
            _votingSystem.RequestVotePlayerList();
            if (_state.CurrentState is LobbyState && VoteTypeButton.SelectedId == (int) StandardVoteType.Restart)
                VoteTypeButton.SelectId((int) StandardVoteType.Map);
            UpdateVoteTimeout();
            // Orbitra edit end
        }

        // Orbitra edit start - очистка работает и при смене экрана или удалении окна.
        protected override void ExitedTree()
        {
            _subscribed = false;
            _state.OnStateChanged -= OnStateChanged;
            _voteManager.CanCallVoteChanged -= CanCallVoteChanged;
            _votingSystem.VotePlayerListResponse -= UpdateVotePlayerList;
            base.ExitedTree();
        }
        // Orbitra edit end

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            UpdateVoteTimeout();
        }

        private void OnStateChanged(StateChangedEventArgs obj)
        {
            if (obj.NewState is not GameplayState)
                return;

            Close();
        }

        private void CanCallVoteChanged(bool obj)
        {
            if (!obj)
                Close();
        }

        private void UpdateVotePlayerList(VotePlayerListResponseEvent msg)
        {
            Dictionary<string, string> optionsList = new();
            Dictionary<NetUserId, (NetEntity, string)> playerList = new();
            foreach ((NetUserId, NetEntity, string) player in msg.Players)
            {
                optionsList.Add(player.Item1.ToString(), player.Item3);
                playerList.Add(player.Item1, (player.Item2, player.Item3));
            }
            PlayerList = playerList;

            IsAllowedVotekick = !msg.Denied;

            var updatedDropdownOption = AvailableVoteOptions[StandardVoteType.Votekick];
            updatedDropdownOption.Dropdowns = new List<Dictionary<string, string>>() { optionsList, VotekickReasons };
            AvailableVoteOptions[StandardVoteType.Votekick] = updatedDropdownOption;
            // Orbitra added start - список может прийти уже после выбора голосования.
            if (VoteTypeButton.SelectedId == (int) StandardVoteType.Votekick)
                RefreshVoteOptions(StandardVoteType.Votekick);
            UpdateVoteTimeout();
            // Orbitra added end
        }

        // Orbitra edit start - используем реальные значения выбранных пунктов.
        private void CreatePressed(BaseButton.ButtonEventArgs obj)
        {
            UpdateVoteTimeout();
            if (CreateButton.Disabled)
                return;

            var type = (StandardVoteType) VoteTypeButton.SelectedId;
            var arguments = new List<string>();
            foreach (var dropdown in VoteOptionsButtonContainer.Children.OfType<OptionButton>())
            {
                if (dropdown.SelectedMetadata is not string key)
                    return;
                arguments.Add(key);
            }

            var suffix = arguments.Count == 0 ? "" : " " + string.Join(' ', arguments);
            _consoleHost.LocalShell.RemoteExecuteCommand($"createvote {type}{suffix}");
            Close();
        }
        // Orbitra edit end

        private void UpdateVoteTimeout()
        {
            var typeKey = (StandardVoteType)VoteTypeButton.SelectedId;
            var isAvailable = _voteManager.CanCallStandardVote(typeKey, out var timeout);

            if (typeKey == StandardVoteType.Restart && _state.CurrentState is LobbyState)
            {
                isAvailable = false;
                timeout = TimeSpan.Zero;
            }

            // Orbitra edit start - создание требует доступного типа и цели.
            var hasNoTargets = typeKey == StandardVoteType.Votekick && IsAllowedVotekick && PlayerList.Count == 0;
            CreateButton.Disabled = !isAvailable || typeKey == StandardVoteType.Votekick && (!IsAllowedVotekick || hasNoTargets);
            VoteTypeTimeoutLabel.Visible = !isAvailable || hasNoTargets;

            var text = isAvailable && !hasNoTargets
                ? null
                : timeout == TimeSpan.Zero || hasNoTargets
                    ? Loc.GetString("ui-vote-type-not-available")
                    : Loc.GetString("ui-vote-type-timeout", ("remaining", (timeout - _gameTiming.RealTime).ToString("mm\\:ss")));
            if (text != _timeoutText)
            {
                _timeoutText = text;
                VoteTypeTimeoutLabel.SetMessage(text ?? "");
            }
            // Orbitra edit end
        }

        private static void ButtonSelected(OptionButton.ItemSelectedEventArgs obj)
        {
            obj.Button.SelectId(obj.Id);
        }

        private void FollowSelected(Button.ButtonEventArgs obj)
        {
            if (_followDropdown == null)
                return;

            if (_followDropdown.SelectedId < 0 || _followDropdown.SelectedId >= PlayerList.Count)
                return;

            var netEntity = PlayerList.ElementAt(_followDropdown.SelectedId).Value.Item1;
            if (!netEntity.Valid) // Orbitra-Edit - у игрока в лобби может ещё не быть сущности.
                return;

            var msg = new GhostWarpToTargetRequestEvent(netEntity);
            _entNetManager.SendSystemNetworkMessage(msg);
        }

        // Orbitra edit start - выбор типа и обновление списка используют один путь.
        private void VoteTypeSelected(OptionButton.ItemSelectedEventArgs obj)
        {
            VoteTypeButton.SelectId(obj.Id);
            RefreshVoteOptions((StandardVoteType) obj.Id);
            UpdateVoteTimeout();
        }

        private void RefreshVoteOptions(StandardVoteType type)
        {
            var option = AvailableVoteOptions[type];
            var votekick = type == StandardVoteType.Votekick;
            VoteNotTrustedLabel.Visible = votekick && !IsAllowedVotekick;
            VoteWarningLabel.Visible = option.EnableVoteWarning;
            FollowButton.Visible = false;
            _followDropdown = null;
            VoteOptionsButtonContainer.RemoveAllChildren();

            if (votekick && (!IsAllowedVotekick || PlayerList.Count == 0))
                return;

            for (var i = 0; i < option.Dropdowns.Count; i++)
            {
                var dropdown = new OrbitraOptionButton { HorizontalExpand = true };
                foreach (var (key, value) in option.Dropdowns[i])
                {
                    var id = dropdown.ItemCount;
                    dropdown.AddItem(value, id);
                    dropdown.SetItemMetadata(id, key);
                }

                OrbitraOptionButton.BindSelection(dropdown, ButtonSelected);
                VoteOptionsButtonContainer.AddChild(dropdown);
                if (option.FollowDropdownId == i)
                {
                    _followDropdown = dropdown;
                    FollowButton.Visible = _state.CurrentState is GameplayState;
                    UpdateFollowButton();
                    OrbitraOptionButton.BindSelection(dropdown, _ => UpdateFollowButton());
                }
            }
        }
        private void UpdateFollowButton()
        {
            var selected = _followDropdown?.SelectedId ?? -1;
            FollowButton.Disabled = selected < 0 || selected >= PlayerList.Count ||
                !PlayerList.ElementAt(selected).Value.Item1.Valid;
        }
        // Orbitra edit end
    }

    [UsedImplicitly, AnyCommand]
    public sealed class VoteMenuCommand : LocalizedCommands
    {
        public override string Command => "votemenu";

        public override void Execute(IConsoleShell shell, string argStr, string[] args)
        {
            new VoteCallMenu().OpenCentered();
        }
    }

    public record struct CreateVoteOption
    {
        public string Name;
        public List<Dictionary<string, string>> Dropdowns;
        public bool EnableVoteWarning;
        public int? FollowDropdownId;  // If set, this will enable the Follow button and use the dropdown matching the ID as input.

        public CreateVoteOption(string name, List<Dictionary<string, string>> dropdowns, bool enableVoteWarning, int? followDropdownId)
        {
            Name = name;
            Dropdowns = dropdowns;
            EnableVoteWarning = enableVoteWarning;
            FollowDropdownId = followDropdownId;
        }
    }
}
